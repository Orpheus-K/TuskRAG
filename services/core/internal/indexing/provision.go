package indexing

import (
	"context"
	"errors"
	"fmt"
	"strconv"
	"time"

	"github.com/jackc/pgx/v5"

	"tuskrag.local/core/internal/db"
	"tuskrag.local/core/internal/dbquery"
)

var (
	ErrProvisioner  = errors.New("database role or schema cannot provision indexes")
	ErrSpaceMissing = errors.New("embedding space is not visible")
	ErrSpaceChanged = errors.New("embedding space changed while provisioning its index")
)

// Provision creates the shared lexical index and one space-specific vector
// index outside a transaction. An invalid or conflicting existing index is
// reported for operator inspection, never dropped automatically.
func Provision(ctx context.Context, databaseURL string, tenantID, spaceID int64) (result error) {
	if ctx == nil || tenantID <= 0 || spaceID <= 0 {
		return errors.New("context, tenant and embedding space are required")
	}
	config, err := pgx.ParseConfig(databaseURL)
	if err != nil {
		return errors.New("invalid index provisioner database configuration")
	}
	conn, err := pgx.ConnectConfig(ctx, config)
	if err != nil {
		return fmt.Errorf("connect index provisioner: %w", err)
	}
	defer func() {
		closeCtx, cancel := context.WithTimeout(context.Background(), 5*time.Second)
		defer cancel()
		if err := conn.Close(closeCtx); err != nil {
			result = errors.Join(result, fmt.Errorf("close index provisioner: %w", err))
		}
	}()
	if _, err := conn.Exec(ctx, `SET search_path = pg_catalog, public`); err != nil {
		return fmt.Errorf("set index search path: %w", err)
	}
	if err := checkProvisioner(ctx, conn); err != nil {
		return err
	}
	queries := dbquery.New(conn)
	// A session lock serializes our DDL without keeping a transaction open.
	// Closing this dedicated connection always releases it.
	if err := acquireProvisioningLock(ctx, queries); err != nil {
		return fmt.Errorf("lock index provisioning: %w", err)
	}
	if _, err := queries.SetIndexTenant(ctx, strconv.FormatInt(tenantID, 10)); err != nil {
		return fmt.Errorf("set index tenant: %w", err)
	}
	args := dbquery.GetIndexSpaceParams{TenantID: tenantID, SpaceID: spaceID}
	profile, err := loadSpace(ctx, queries, args)
	if err != nil {
		return err
	}
	definitions, err := indexDefinitions(spaceID, profile.Dims, profile.Distance)
	if err != nil {
		return err
	}
	for _, item := range definitions {
		if err := ensureIndex(ctx, conn, item); err != nil {
			return err
		}
	}
	current, err := loadSpace(ctx, queries, args)
	if err != nil {
		return err
	}
	if current != profile {
		return ErrSpaceChanged
	}
	for _, item := range definitions {
		if err := checkDefinition(ctx, conn, item); err != nil {
			return err
		}
	}
	return nil
}

func acquireProvisioningLock(ctx context.Context, queries *dbquery.Queries) error {
	for {
		locked, err := queries.TryLockIndexProvisioning(ctx)
		if err != nil {
			return err
		}
		if locked {
			return nil
		}
		// A blocking advisory-lock statement retains a snapshot and can
		// deadlock with CREATE INDEX CONCURRENTLY waiting for old snapshots.
		timer := time.NewTimer(100 * time.Millisecond)
		select {
		case <-ctx.Done():
			timer.Stop()
			return ctx.Err()
		case <-timer.C:
		}
	}
}

func loadSpace(ctx context.Context, queries *dbquery.Queries, args dbquery.GetIndexSpaceParams) (dbquery.GetIndexSpaceRow, error) {
	row, err := queries.GetIndexSpace(ctx, args)
	if errors.Is(err, pgx.ErrNoRows) {
		return dbquery.GetIndexSpaceRow{}, ErrSpaceMissing
	}
	if err != nil {
		return dbquery.GetIndexSpaceRow{}, fmt.Errorf("load index space: %w", err)
	}
	return row, nil
}

func ensureIndex(ctx context.Context, conn *pgx.Conn, item definition) error {
	err := checkDefinition(ctx, conn, item)
	if err == nil {
		return nil
	}
	if !errors.Is(err, ErrIndexMissing) {
		return err
	}
	// Identifiers and dimensions are generated solely from validated integers.
	if _, err := conn.Exec(ctx, item.ddl); err != nil {
		return fmt.Errorf("create index %s: %w", item.name, err)
	}
	return checkDefinition(ctx, conn, item)
}

func checkProvisioner(ctx context.Context, conn *pgx.Conn) error {
	var pg17, unprivileged, ownsTables, vector, search, schema bool
	// These PostgreSQL catalog queries cannot be generated by offline sqlc.
	err := conn.QueryRow(ctx, `SELECT current_setting('server_version_num')::int / 10000 = 17,
		NOT r.rolsuper AND NOT r.rolbypassrls,
		(SELECT count(*) = 2 FROM pg_catalog.pg_class c JOIN pg_catalog.pg_namespace n ON n.oid = c.relnamespace
		 WHERE n.nspname = 'public' AND c.relname IN ('chunk', 'chunk_vector')
		 AND c.relowner = r.oid AND c.relrowsecurity AND c.relforcerowsecurity),
		EXISTS (SELECT 1 FROM pg_catalog.pg_extension WHERE extname = 'vector' AND extversion = '0.8.1'),
		EXISTS (SELECT 1 FROM pg_catalog.pg_extension WHERE extname = 'pg_search' AND extversion = '0.22.6'),
		COALESCE((SELECT version_id = $1 AND is_applied FROM public.goose_db_version ORDER BY id DESC LIMIT 1), false)
		FROM pg_catalog.pg_roles r WHERE r.rolname = current_user`, db.SchemaVersion).Scan(&pg17, &unprivileged, &ownsTables, &vector, &search, &schema)
	if err != nil {
		return fmt.Errorf("check index provisioner: %w", err)
	}
	if !pg17 || !unprivileged || !ownsTables || !vector || !search || !schema {
		return ErrProvisioner
	}
	return nil
}
